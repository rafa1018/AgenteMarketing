// Share image (Open Graph 1200×630) for WhatsApp, Facebook, Instagram, Telegram, X…
// Run with: npm run og   (also runs at the end of `npm run images`)
import sharp from 'sharp'
import { existsSync } from 'node:fs'

const OUT = 'public/images/og-image.jpg'
const C = { ink: '#23206b', pink: '#e5197e', yellow: '#f8c21c', blue: '#1fa3dd', green: '#5cb531', orange: '#f26b1d' }
const font = "'Segoe UI', Arial, Helvetica, sans-serif"

const svg = `
<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630">
  <defs>
    <linearGradient id="sky" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#bfe8ff"/><stop offset="1" stop-color="#eef9ff"/></linearGradient>
  </defs>
  <rect width="1200" height="630" fill="url(#sky)"/>
  <g fill="#ffffff">
    <ellipse cx="180" cy="110" rx="90" ry="30"/><ellipse cx="230" cy="92" rx="60" ry="34"/>
    <ellipse cx="980" cy="80" rx="80" ry="26"/><ellipse cx="1030" cy="64" rx="52" ry="30"/>
  </g>
  <text x="520" y="300" font-family="${font}" font-weight="800" font-size="46" fill="${C.ink}">Jardín Infantil en Valledupar</text>
  <text x="520" y="352" font-family="${font}" font-weight="600" font-size="30" fill="${C.pink}">Creciendo con las artes</text>
  <text x="520" y="404" font-family="${font}" font-weight="600" font-size="24" fill="${C.ink}" fill-opacity=".8">Párvulos · Prejardín · Jardín · Transición</text>
  <rect x="520" y="432" width="300" height="56" rx="28" fill="${C.yellow}"/>
  <text x="670" y="468" text-anchor="middle" font-family="${font}" font-weight="800" font-size="24" fill="${C.ink}">Inscripciones abiertas</text>
  <rect x="0" y="560" width="1200" height="70" fill="${C.ink}"/>
  <text x="600" y="604" text-anchor="middle" font-family="${font}" font-weight="700" font-size="24" fill="#ffffff">gabushkids.com  ·  @jardin_gabush  ·  Urb. Colombia, Valledupar</text>
</svg>`

// the hero lion (eyes open), generated by scripts/characters.mjs
const LION = 'public/images/characters/leon-open-800.webp'
const lion = await sharp(existsSync(LION) ? LION : 'public/images/gabushV2.png').trim({ threshold: 2 }).resize({ height: 470 }).png().toBuffer()
const logo = await sharp('public/images/logo.png').trim({ threshold: 2 }).resize({ width: 560 }).png().toBuffer()

await sharp(Buffer.from(svg))
  .composite([
    { input: lion, left: 60, top: 80 },
    { input: logo, left: 515, top: 40 },
  ])
  .jpeg({ quality: 88, mozjpeg: true })
  .toFile(OUT)

console.log(`[og] ${OUT} 1200×630`)
